"""GBNF + JSON grammar artifacts for constrained decoding (issue #162).

Source is `vocabulary_document()` (`impl/lnpl/vocab.py`) — this module never
re-derives from `impl/lnpl/spec.py`/`lower.py`/`types.py` directly. Scope is
the closed-vocabulary tokens only (verbs, keywords, types, clauses, spec
`given`/`expect` forms) — no program-structure grammar, no inference-engine
integration. Never hand-edit `schemas/lnpl-grammar.gbnf` or
`schemas/lnpl-grammar.json`; both are generated by
`python scripts/gen_plugin_references.py` from the functions below. The editor
grammars under `editors/` (tree-sitter + TextMate, issue #254) are generated by
the same script from the `render_*` functions and are never hand-edited either.
"""

import json
import re

from lnpl.vocab import vocabulary_document

_BANNER = ("# generated — do not hand-edit. "
           "source: impl/lnpl/grammar.py:render_gbnf(). "
           "regenerate: python scripts/gen_plugin_references.py\n")

# (rule name, comment, vocab -> list[str] of terminal alternatives)
_RULES = (
    ("verb", None, lambda vocab: sorted(vocab["verbs"])),
    ("top_keyword", None, lambda vocab: list(vocab["keywords"]["top"])),
    ("clause_keyword", None, lambda vocab: list(vocab["keywords"]["clause"])),
    ("control_keyword", None,
     lambda vocab: list(vocab["keywords"]["control"])),
    ("semantic_type", None, lambda vocab: sorted(vocab["types"]["semantic"])),
    ("comparator", None, lambda vocab: list(vocab["keywords"]["comparators"])),
    ("arithmetic_op", None,
     lambda vocab: list(vocab["keywords"]["arithmetic_operators"])),
    ("logical_op", None,
     lambda vocab: list(vocab["keywords"]["logical_operators"])),
    ("policy_clause", None, lambda vocab: list(vocab["clauses"]["policy"])),
    ("security_clause", None,
     lambda vocab: list(vocab["clauses"]["security"])),
    ("performance_clause", None,
     lambda vocab: list(vocab["clauses"]["performance"])),
    ("spec_expect", None,
     lambda vocab: list(vocab["spec_expectations"]["expects"])),
    ("spec_given_form",
     "# spec_given_form enumerates the closed set of given-form TEMPLATES "
     "(patterns contain <field>-style placeholders), documenting which forms "
     "exist — it is not a decoding constraint for concrete given-clauses.",
     lambda vocab: [entry["pattern"]
                    for entry in vocab["spec_expectations"]["given_forms"]]),
)

# rule -> (TextMate scope, tree-sitter highlight capture). Keys must equal the
# `_RULES` names minus "spec_given_form" (test_editor_grammars pins it).
_EDITOR_SCOPES = {
    "verb": ("keyword.other.verb.lnpl", "@function"),
    "top_keyword": ("storage.type.lnpl", "@keyword"),
    "clause_keyword": ("keyword.other.clause.lnpl", "@keyword"),
    "control_keyword": ("keyword.control.lnpl", "@keyword"),
    "semantic_type": ("support.type.lnpl", "@type"),
    "comparator": ("keyword.operator.comparison.lnpl", "@operator"),
    "arithmetic_op": ("keyword.operator.arithmetic.lnpl", "@operator"),
    "logical_op": ("keyword.operator.logical.lnpl", "@operator"),
    "policy_clause": ("support.constant.policy.lnpl", "@property"),
    "security_clause": ("support.constant.security.lnpl", "@property"),
    "performance_clause": ("support.constant.performance.lnpl", "@property"),
    "spec_expect": ("support.function.spec.lnpl", "@attribute"),
}
# Classes allowed only as the first token of a line, in both editor grammars.
_HEAD_ONLY = ("verb", "spec_expect")


def _gbnf_quote(token):
    escaped = token.replace("\\", "\\\\").replace('"', '\\"')
    return '"%s"' % escaped


def render_gbnf(vocab=None):
    """GBNF text: one rule per closed set, in `_RULES` order."""
    vocab = vocab or vocabulary_document()
    lines = [_BANNER]
    for name, comment, source in _RULES:
        if comment is not None:
            lines.append(comment + "\n")
        alternatives = " | ".join(_gbnf_quote(item) for item in source(vocab))
        lines.append("%s ::= %s\n" % (name, alternatives))
    return "".join(lines)


def grammar_json_document(vocab=None):
    """JSON manifest: the vocabulary document plus a `_generated` marker."""
    vocab = vocab or vocabulary_document()
    return {
        "_generated": {
            "by": "scripts/gen_plugin_references.py",
            "source": "impl/lnpl/grammar.py:grammar_json_document()",
            "hand_edit": False,
        },
        "vocabulary": vocab,
    }


def _highlight_classes(vocab):
    """(rule, tokens) per highlight class in `_RULES` order. A token claimed by
    an earlier rule is dropped from later ones; an empty class is skipped."""
    claimed = set()
    classes = []
    for name, _comment, source in _RULES:
        if name == "spec_given_form":
            continue
        tokens = [t for t in source(vocab) if t not in claimed]
        claimed.update(tokens)
        if tokens:
            classes.append((name, tokens))
    return classes


def render_tree_sitter(vocab=None):
    """tree-sitter `grammar.js`: a line-structured token grammar, one rule per
    highlight class. Verbs and spec expectations are head-only."""
    vocab = vocab or vocabulary_document()
    classes = _highlight_classes(vocab)
    names = [name for name, _tokens in classes]
    head = ", ".join("$.%s" % name for name in names)
    args = ", ".join("$.%s" % name for name in names if name not in _HEAD_ONLY)
    lines = [
        "// generated — do not hand-edit. "
        "source: impl/lnpl/grammar.py:render_tree_sitter(). "
        "regenerate: python scripts/gen_plugin_references.py",
        "module.exports = grammar({",
        "  name: 'lnpl',",
        "  extras: $ => [/[ \\f\\v\\r]/, $.comment],",
        "  word: $ => $.identifier,",
        "  rules: {",
        "    source_file: $ => seq(optional($.line), "
        "repeat(seq($._newline, optional($.line)))),",
        "    line: $ => seq($._head, repeat($._arg)),",
        "    _head: $ => choice(%s, $.identifier)," % head,
        "    _arg: $ => choice(%s, $.identifier)," % args,
        "    _newline: $ => /\\n/,",
    ]
    for name, tokens in classes:
        if len(tokens) == 1:
            body = json.dumps(tokens[0])
        else:
            body = "choice(%s)" % ", ".join(json.dumps(t) for t in tokens)
        lines.append("    %s: $ => %s," % (name, body))
    lines += [
        "    identifier: $ => /[^\\s#]+/,",
        "    comment: $ => token(seq('#', /.*/)),",
        "  },",
        "});",
    ]
    return "".join(line + "\n" for line in lines)


def render_tree_sitter_highlights(vocab=None):
    """tree-sitter `queries/highlights.scm`: one capture per highlight class."""
    vocab = vocab or vocabulary_document()
    lines = ["; generated — do not hand-edit. "
             "source: impl/lnpl/grammar.py:render_tree_sitter_highlights(). "
             "regenerate: python scripts/gen_plugin_references.py\n"]
    for name, _tokens in _highlight_classes(vocab):
        lines.append("(%s) %s\n" % (name, _EDITOR_SCOPES[name][1]))
    lines.append("(comment) @comment\n")
    return "".join(lines)


def render_textmate(vocab=None):
    """TextMate grammar (VS Code `lnpl.tmLanguage.json`), sorted-key JSON."""
    vocab = vocab or vocabulary_document()
    patterns = [{"name": "comment.line.number-sign.lnpl", "match": "#.*$"}]
    for name, tokens in _highlight_classes(vocab):
        scope = _EDITOR_SCOPES[name][0]
        alts = "|".join(re.escape(t) for t in tokens)
        if name in _HEAD_ONLY:
            patterns.append({"match": "^\\s*(" + alts + ")(?!\\S)",
                             "captures": {"1": {"name": scope}}})
        else:
            patterns.append({"name": scope,
                             "match": "(?<!\\S)(" + alts + ")(?!\\S)"})
    doc = {
        "_generated": {
            "by": "scripts/gen_plugin_references.py",
            "source": "impl/lnpl/grammar.py:render_textmate()",
            "hand_edit": False,
        },
        "name": "LNPL",
        "scopeName": "source.lnpl",
        "fileTypes": ["lnpl"],
        "patterns": patterns,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
